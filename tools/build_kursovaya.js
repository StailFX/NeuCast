body.push(pBody('Б.3. NNLS-стэкинг весов ансамбля моделей (см. §3.3):'));
const codeNNLS = [
  'from scipy.optimize import nnls',
  '',
  'def fit_ensemble_weights(val_preds, val_truth):',
  '    """Подбирает неотрицательные веса w ансамбля так, чтобы',
  '    минимизировать ||val_truth - val_preds @ w||² при ограничении',
  '    Σ wᵢ = 1, wᵢ ≥ 0. Решение через алгоритм Лоусона-Хансона (NNLS)',
  '    + проекция результата на симплекс через L1-нормализацию.',
  '',
  '    val_preds: np.ndarray формы (n_samples, n_models) — out-of-fold',
  '               предсказания каждой модели на валидационной выборке.',
  '    val_truth: np.ndarray формы (n_samples,) — фактические значения.',
  '    """',
  '    # NNLS даёт неотрицательное решение без simplex-ограничения.',
  '    weights, residual = nnls(val_preds, val_truth)',
  '',
  '    # Проекция на симплекс: если решение нулевое (вырожденный случай),',
  '    # возвращаем равномерные веса; иначе нормируем сумму до единицы.',
  '    total = weights.sum()',
  '    if total < 1e-9:',
  '        n_models = val_preds.shape[1]',
  '        return np.ones(n_models) / n_models',
  '    return weights / total',
  '',
  '',
  'def direction_aware_blend(nnls_weights, val_dir_accuracy, alpha=0.5):',
  '    """Direction-aware blend: NNLS оптимизирует MAPE, но не направление.',
  '    Если все модели имеют похожий MAPE, NNLS может присвоить вес 1.0',
  '    одной случайной — что плохо для directional accuracy. Подмешиваем',
  '    веса, пропорциональные excess_dir = max(0, dir_acc - 0.5).',
  '    """',
  '    excess = np.maximum(0.0, val_dir_accuracy - 0.5)',
  '    total_skill = excess.sum()',
  '    if total_skill <= 0:',
  '        return nnls_weights  # никто не лучше монетки',
  '    dir_weights = excess / total_skill',
  '    blended = (1 - alpha) * nnls_weights + alpha * dir_weights',
  '    return blended / blended.sum()',
];

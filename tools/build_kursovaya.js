// Bullet list paragraph (uses "—" dash per памятка's «перечисления с тире»).
function pDash(text) {
  return new Paragraph({
    spacing: { ...LINE, before: 0, after: 0 },
    indent: { left: INDENT, hanging: 284 }, // hanging "— "
    alignment: AlignmentType.JUSTIFIED,
    children: [
      new TextRun({ text: '— ' + text, font: FONT, size: SZ_BODY }),
    ],
  });
}

// Numbered list (manual since list-numbering requires global config).

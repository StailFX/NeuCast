body.push(pBody('Б.2. Walk-forward валидация с эмбарго (см. §3.5):'));
const codeWalkForward = [
  'def walk_forward_cv(',
  '    X, y, initial_train_bars, test_fold_bars, step_bars, embargo=1,',
  '):',
  '    """Walk-forward валидация: модель обучается на интервале [0, t_end),',
  '    прогнозирует на [t_end, t_end + test_fold_bars), затем окно',
  '    сдвигается на step_bars. Между обучающим и тестовым интервалом',
  '    оставляется embargo баров — это предотвращает утечку через',
  '    общие признаки, рассчитанные по скользящему окну.',
  '    """',
  '    n = len(X)',
  '    train_end = initial_train_bars',
  '    oos_preds, oos_truth = [], []',
  '',
  '    while train_end + test_fold_bars <= n:',
  '        # Effective training end отступает на embargo баров.',
  '        train_eff_end = max(0, train_end - embargo)',
  '        X_train = X[:train_eff_end]',
  '        y_train = y[:train_eff_end]',
  '        X_test = X[train_end : train_end + test_fold_bars]',
  '        y_test = y[train_end : train_end + test_fold_bars]',
  '',
  '        # Игнорируем фолд если данных слишком мало или один класс.',
  '        if len(X_train) < 100 or len(set(y_train.flatten())) < 2:',
  '            train_end += step_bars',
  '            continue',
  '',
  '        model = clone_estimator()  # свежий экземпляр на каждом фолде',
  '        model.fit(X_train, y_train)',
  '        oos_preds.extend(model.predict(X_test))',
  '        oos_truth.extend(y_test)',
  '        train_end += step_bars',
  '',
  '    return np.array(oos_preds), np.array(oos_truth)',
];

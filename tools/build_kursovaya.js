const codeTCN = [
  'def tcn_block(x, filters, kernel_size=3, dilation_rate=1, dropout=0.2):',
  '    """Один блок TCN: две причинные свёртки с расширением + residual.',
  '',
  '    Причинность обеспечивается через padding="causal" — выход в момент t',
  '    зависит только от входа на интервале [t - (k-1)*d, t]. Расширение d',
  '    экспоненциально увеличивает рецептивное поле без роста числа слоёв.',
  '    """',
  '    # Первая причинная свёртка с расширением',
  '    y = Conv1D(filters, kernel_size,',
  '               padding="causal", dilation_rate=dilation_rate)(x)',
  '    y = BatchNormalization()(y)',
  '    y = Activation("relu")(y)',
  '    y = Dropout(dropout)(y)',
  '',
  '    # Вторая причинная свёртка',
  '    y = Conv1D(filters, kernel_size,',
  '               padding="causal", dilation_rate=dilation_rate)(y)',
  '    y = BatchNormalization()(y)',
  '    y = Activation("relu")(y)',
  '    y = Dropout(dropout)(y)',
  '',
  '    # Residual-связь: проброс входа мимо нелинейных преобразований.',
  '    # Если число каналов различается, добавляем 1x1-свёртку для матчинга.',
  '    if x.shape[-1] != filters:',
  '        x = Conv1D(filters, kernel_size=1, padding="same")(x)',
  '    return Add()([x, y])',
  '',
  '',
  'def build_tcn_model(seq_len, n_features, dilations=(1, 2, 4, 8)):',
  '    """Стек из 4 блоков с dilation rates {1, 2, 4, 8} и финальной регрессией."""',
  '    inputs = Input(shape=(seq_len, n_features))',
  '    x = inputs',
  '    for d in dilations:',
  '        x = tcn_block(x, filters=64, kernel_size=3, dilation_rate=d)',
  '    x = GlobalAveragePooling1D()(x)',
  '    out = Dense(1)(x)  # регрессия log-return на следующий шаг',
  '    return Model(inputs, out)',
];

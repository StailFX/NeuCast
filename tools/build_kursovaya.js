  '    Применяется формула:',
  '        ŷ_corrected = ŷ_ensemble · (1 + α · s_avg · min(1, n / N_full))',
  '',
  '    Множитель min(1, n / N_full) обеспечивает плавное «включение»',
  '    sentiment-сигнала при росте числа новостей и предотвращает',
  '    переоценку слабого сигнала на скудных данных.',
  '    """',
  '    if total_articles <= 0 or not result.get("future_preds"):',
